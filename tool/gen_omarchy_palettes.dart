// Generates lib/core/theme/omarchy_palettes.g.dart from the Omarchy themes.
// Needs dart:ui (via omarchy_colors.dart), so run it through the Flutter
// test runner:
//   flutter test tool/gen_omarchy_palettes.dart
// Optional: OMARCHY_THEMES=/path/to/themes (default /usr/share/omarchy/themes).
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:material_ui/material_ui.dart' show Color;
import 'package:watchdog/core/theme/omarchy_colors.dart';

/// Hand-tuned palettes already in palettes.dart.
const skip = {'everforest', 'tokyo-night', 'catppuccin-latte'};

String hex(Color c) =>
    'Color(0xFF${(c.toARGB32() & 0xFFFFFF).toRadixString(16).toUpperCase().padLeft(6, '0')})';

String pretty(String id) => id
    .split('-')
    .map((w) => w.isEmpty ? w : w[0].toUpperCase() + w.substring(1))
    .join(' ');

void main() {
  test('generate omarchy_palettes.g.dart', () {
    final root = Directory(
      Platform.environment['OMARCHY_THEMES'] ?? '/usr/share/omarchy/themes',
    );
    final dirs = root.listSync().whereType<Directory>().toList()
      ..sort((a, b) => a.path.compareTo(b.path));
    final out = StringBuffer()
      ..writeln('// GENERATED by tool/gen_omarchy_palettes.dart. Do not edit.')
      ..writeln("import 'package:material_ui/material_ui.dart';")
      ..writeln()
      ..writeln("import 'palettes.dart';")
      ..writeln()
      ..writeln(
        '/// Built-in Omarchy themes, self-contained (no Omarchy needed).',
      )
      ..writeln('const omarchyPalettes = <AppPalette>[');
    for (final d in dirs) {
      final id = d.path.split('/').last;
      final f = File('${d.path}/colors.toml');
      if (skip.contains(id) || !f.existsSync()) continue;
      final p = OmarchyColors.parse(f.readAsStringSync())
          .toPalette(id: id, name: pretty(id));
      if (p == null) continue;
      out
        ..writeln('  AppPalette(')
        ..writeln("    id: '$id',")
        ..writeln("    name: '${p.name}',")
        ..writeln('    dark: ${p.dark},')
        ..writeln('    bg: ${hex(p.bg)},')
        ..writeln('    bar: ${hex(p.bar)},')
        ..writeln('    card: ${hex(p.card)},')
        ..writeln('    highlight: ${hex(p.highlight)},')
        ..writeln('    border: ${hex(p.border)},')
        ..writeln('    text: ${hex(p.text)},')
        ..writeln('    muted: ${hex(p.muted)},')
        ..writeln('    accent: ${hex(p.accent)},')
        ..writeln('    onAccent: ${hex(p.onAccent)},')
        ..writeln('    ok: ${hex(p.ok)},')
        ..writeln('    error: ${hex(p.error)},')
        ..writeln('  ),');
    }
    out.writeln('];');
    File('lib/core/theme/omarchy_palettes.g.dart').writeAsStringSync('$out');
  });
}
